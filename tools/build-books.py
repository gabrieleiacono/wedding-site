#!/usr/bin/env python3
"""Collects the spine research (knowledge/spines/group-*.json in the project files) into src/books-data.js.
Usage: python3 tools/build-books.py [spines_dir]"""
import glob, json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'knowledge', 'spines')
KEEP = ('author', 'title', 'publisher', 'series', 'year', 'first_published', 'height_mm', 'width_mm', 'thickness_mm', 'binding', 'spine')
books, seen = [], set()
for path in sorted(glob.glob(os.path.join(src, 'group-*.json'))):
    try:
        data = json.load(open(path, encoding='utf-8'))
    except Exception as e:  # a research thread may be mid-write
        print('skip', path, e); continue
    items = data.get('books', data) if isinstance(data, dict) else data
    for b in items if isinstance(items, list) else []:
        if not isinstance(b, dict) or not b.get('title'):
            continue
        key = (b.get('author', '').lower(), b['title'].lower())
        if key in seen:
            continue
        seen.add(key)
        books.append({k: b[k] for k in KEEP if k in b and b[k] is not None})
out = os.path.join(here, '..', 'src', 'books-data.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build-books.py from the spine research. Do not edit by hand.\n')
    f.write('export const BOOKS = ' + json.dumps(books, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(books), 'books ->', os.path.relpath(out))
