#!/usr/bin/env python3
"""Collects the spine research (knowledge/spines/group-*.json in the project files) into src/books-data.js.
Each title goes on the shelf once: of several editions, an Einaudi Super ET wins, then another
Einaudi paperback, then the research's first pick (batch 1) over its later extras.
Usage: python3 tools/build-books.py [spines_dir]"""
import glob, json, os, re, sys, unicodedata

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'knowledge', 'spines')
KEEP = ('author', 'title', 'publisher', 'series', 'year', 'first_published', 'height_mm', 'width_mm', 'thickness_mm', 'binding', 'spine')


# Works that one edition retitles: (surname, title as work() reduces it) -> the usual title
ALIASES = {('roth', 'portnoy'): 'lamento di portnoy', ('dick', 'ma androidi sognano pecore elettriche'): 'androidi sognano pecore elettriche'}


def work(b):
    """The same work in any edition: the author's surname and the title without its subtitle (unless it
    names a volume), accents, punctuation or articles."""
    t = b['title'] if re.search(r'\bvol', b['title'], re.I) else re.split(r'\.\s|:\s|\s[-–]\s|\s\(', b['title'])[0]
    t = unicodedata.normalize('NFKD', t).encode('ascii', 'ignore').decode().lower()
    t = re.sub(r"[^a-z0-9]+", ' ', t)
    t = ' '.join(re.sub(r'\b(il|lo|la|i|gli|le|l|un|una|uno)\b', ' ', t).split())
    a = (str(b.get('author', '')).split()[-1:] or [''])[0].lower()
    return a, ALIASES.get((a, t), t)


def rank(b):
    pub, ser = str(b.get('publisher', '')).lower(), str(b.get('series', '')).lower()
    if 'einaudi' in pub:
        if 'super et' in ser:
            return 0
        if re.match(r'\s*(et\b|einaudi tascabili)', ser):
            return 1
        return 2 if b.get('binding', 'paperback') == 'paperback' else 3
    return 4 if b.get('batch', 1) == 1 else 5


best, order = {}, []
for path in sorted(glob.glob(os.path.join(src, 'group-*.json'))):
    try:
        data = json.load(open(path, encoding='utf-8'))
    except Exception as e:  # a research thread may be mid-write
        print('skip', path, e); continue
    items = data.get('books', data) if isinstance(data, dict) else data
    for b in items if isinstance(items, list) else []:
        if not isinstance(b, dict) or not b.get('title'):
            continue
        k = work(b)
        if k not in best:
            order.append(k); best[k] = b
        elif rank(b) < rank(best[k]):
            print('  keep', b['title'], '|', b.get('series'), '  over', best[k].get('series'))
            best[k] = b
        else:
            print('  drop', b['title'], '|', b.get('series'), '  (have', best[k].get('series'), ')')
books = [{f: best[k][f] for f in KEEP if f in best[k] and best[k][f] is not None} for k in order]
out = os.path.join(here, '..', 'src', 'books-data.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build-books.py from the spine research. Do not edit by hand.\n')
    f.write('export const BOOKS = ' + json.dumps(books, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(books), 'books ->', os.path.relpath(out))
